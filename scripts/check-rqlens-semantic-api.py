#!/usr/bin/env python3
"""Real CLI/compiler probe for RQLens rustdoc-json-v1 (Rust 1.95 / format 57).

Run inside nix develop with a frozen executable and independently frozen helper
manifest. Positive proof uses actual embedded compiler JSON; handwritten mutations
are confined to named negative decoder cases. Experimental bootstrap is explicit,
never a claim that stable Rust supports unstable rustdoc JSON.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys


SOURCE = '''//! Compiler-visible API with explicit reachability and trait witnesses.

mod implementation {
    /// Exported through a private-module reexport, not its original path.
    #[derive(Debug)]
    pub struct Reexported {
        /// The exported field.
        pub value: u8,
        private: u8,
    }

    /// Syntactically public but unreachable outside this private module.
    pub struct Unreachable;

    #[doc(hidden)]
    pub struct HiddenInPrivate;

    struct Private;
}

/// The externally visible name of the private-module item.
pub use implementation::Reexported as PublicAlias;

/// A second local alias; not a second nominal type.
pub type SecondAlias = PublicAlias;

/// A local trait whose name must not be confused with core::fmt::Debug.
pub trait Debug {}

/// Implements only the local Debug trait.
pub struct LocalDebugOnly;
impl Debug for LocalDebugOnly {}

macro_rules! generate_api {
    ($name:ident) => {
        /// An API type generated by a macro.
        #[derive(Debug)]
        pub struct $name;
    };
}
generate_api!(Generated);

#[doc(hidden)]
pub struct HiddenAtRoot;

/// Compiled by rustdoc's cfg(doc), not ordinary Cargo checking.
#[cfg(doc)]
#[must_use]
pub fn doc_only() -> u8 {
    1
}

/// Not part of this cfg(doc) capture.
#[cfg(not(doc))]
#[must_use]
pub fn runtime_only() -> u8 {
    2
}

/// Enabled only in the extra Cargo feature capture.
#[cfg(feature = "extra")]
pub struct FeatureOnly;

/// A dependency reexport; target docs/traits need actual external evidence.
#[doc(no_inline)]
pub use api_dependency::External as ExternalAlias;
'''

GLOB_CYCLE = '''//! Valid cyclic glob exports require bounded graph traversal.

/// Left export surface.
pub mod left {
    pub use crate::right::*;
}

/// Right export surface.
pub mod right {
    pub use crate::left::*;
    /// A real terminal item behind the reexport cycle.
    pub struct Terminal;
}
'''

BROKEN_CYCLE = '''//! An unresolved reexport cycle must fail compilation, not reuse old JSON.

mod left {
    pub use crate::right::Missing;
}
mod right {
    pub use crate::left::Missing;
}
/// This cannot resolve without a real base definition.
pub use left::Missing;
'''


def require(condition, message):
    if not condition:
        raise AssertionError(message)


def execute(command, directory, name, environment=None, timeout=180):
    with (directory / f"{name}.stdout.log").open("w") as stdout:
        with (directory / f"{name}.stderr.log").open("w") as stderr:
            outcome = subprocess.run(
                list(map(str, command)), stdin=subprocess.DEVNULL,
                stdout=stdout, stderr=stderr, env=environment,
                timeout=timeout, check=False,
            )
    return outcome.returncode


def setup(directory, source=SOURCE):
    (directory / "src").mkdir(parents=True, exist_ok=False)
    (directory / "src/lib.rs").write_text(source)
    (directory / "dependency/src").mkdir(parents=True)
    (directory / "dependency/Cargo.toml").write_text(
        '[package]\nname = "api-dependency"\nversion = "0.0.0"\n'
        'edition = "2024"\nrust-version = "1.95"\nlicense = "MIT"\n'
    )
    (directory / "dependency/src/lib.rs").write_text(
        '//! Actual local dependency, outside the consumer source-root inventory.\n'
        '/// A dependency-owned type.\n#[derive(Debug)]\npub struct External;\n'
    )
    (directory / "Cargo.toml").write_text(
        '[package]\nname = "rqlens-semantic-consumer"\nversion = "0.0.0"\n'
        'edition = "2024"\nrust-version = "1.95"\nlicense = "MIT"\n'
        '[features]\ndefault = []\nextra = []\n'
        '[dependencies]\napi-dependency = { path = "dependency" }\n'
    )
    cargo = shutil.which("cargo")
    require(cargo is not None, "real Cargo required")
    for name, command in (
        ("format", [cargo, "fmt", "--manifest-path", directory / "Cargo.toml"]),
        ("lock", [cargo, "generate-lockfile", "--offline", "--manifest-path", directory / "Cargo.toml"]),
    ):
        require(execute(command, directory, name) == 0, f"fixture {name} failed")
    return cargo


def compiler_capture(directory, name, experimental, features=()):
    """Preparation/oracle capture, not a replacement for RQLens execution evidence."""
    environment = os.environ.copy()
    environment.pop("RUSTC_BOOTSTRAP", None)
    if experimental:
        environment["RUSTC_BOOTSTRAP"] = "1"
    target = directory / (name + "-target")
    environment["CARGO_TARGET_DIR"] = str(target)
    command = ["cargo", "rustdoc", "--locked", "--offline", "--lib",
               "--manifest-path", directory / "Cargo.toml"]
    if features:
        command += ["--features", ",".join(features)]
    command += ["--", "-Z", "unstable-options", "--output-format", "json"]
    code = execute(command, directory, name, environment)
    output = target / "doc/rqlens_semantic_consumer.json"
    identity = {
        "command": list(map(str, command)), "exit_code": code,
        "RUSTC_BOOTSTRAP": environment.get("RUSTC_BOOTSTRAP"),
        "features": list(features), "output_exists": output.is_file(),
    }
    if output.is_file():
        raw = output.read_bytes()
        document = json.loads(raw)
        identity.update({"output_sha256": hashlib.sha256(raw).hexdigest(),
                         "format_version": document["format_version"],
                         "root": document["root"], "index_count": len(document["index"])})
    (directory / (name + "-capture.json")).write_text(json.dumps(identity, indent=2) + "\n")
    return code, output


def write_config(directory, helper, backend="rustdoc-json-v1", features=(), workspace=False,
                 exclude=(), target=None):
    config = directory / "rqlens.toml"
    text = (
        'project_root = "."\nsource_roots = ["src"]\noutput_dir = "artifacts"\n'
        '[rust]\nidentity_resolution = "auto"\nidentity_offline = true\n'
        f'helper_manifest = {json.dumps(str(helper))}\n'
        '[verification]\ntimeout_seconds = 120\nlocked = true\n'
        f'workspace = {str(workspace).lower()}\nall_targets = false\nall_features = false\n'
        f'features = {json.dumps(list(features))}\nexclude = {json.dumps(list(exclude))}\n'
    )
    if backend is not None:
        text += f'public_api_backend = {json.dumps(backend)}\n'
    if target:
        text += f'public_api_target = {json.dumps(target)}\n'
    config.write_text(text)
    return config


def environment(experimental=False, **overrides):
    result = os.environ.copy()
    result.pop("RUSTC_BOOTSTRAP", None)
    result.pop("RUSTDOC", None)
    result.pop("RUSTDOCFLAGS", None)
    result.pop("CARGO_ENCODED_RUSTDOCFLAGS", None)
    if experimental:
        result["RUSTC_BOOTSTRAP"] = "1"
    result.update(overrides)
    return result


def measure(tool, directory, config, phase, env):
    code = execute([tool, "measure", "semantic-api", "--config", config],
                   directory, phase, env)
    require(code == 0, f"producer exit {code}; see {phase} logs")
    report = json.loads((directory / "artifacts/semantic_api.json").read_text())
    (directory / f"{phase}-report.json").write_text(json.dumps(report, indent=2) + "\n")
    return report["data"]


def unavailable(data):
    require(data["summary"]["item_count"] is None, "unavailable semantic inventory became verified API zero")
    require(not data.get("items"), "unavailable capture reused prior compiler definitions")
    require(data["measurement_confidence"]["complete"] is False, "unavailable evidence marked complete")


def completed_context(data):
    require(data["backend"] == "rustdoc-json-v1" and data["model_version"] == 1, "wrong backend/model")
    contexts = [c for c in data["contexts"] if c["status"] == "completed"]
    require(len(contexts) == 1, f"expected one completed library context: {data['summary']}, {data.get('failures')}")
    context = contexts[0]
    raw = context["capture"]["raw_document"]
    require(raw["format_version"] == 57 and raw["includes_private"] is False, "unsupported/private compiler scope")
    require(context["capture"]["fresh_directory"] is True and
            context["capture"]["output_reused_after_failure"] is False, "capture freshness provenance absent")
    require(context["capture"]["format_version"] == 57 and context["capture"]["output_digest"], "capture identity absent")
    scope = data["scope"]
    require(scope["cfg_doc"] is True and scope["document_hidden_items"] is False and
            scope["hidden_reachable_language_api_excluded"] is True and
            scope["document_private_items"] is False and scope["source_syntax_fallback"] is False,
            "rustdoc public/nonhidden/cfg(doc) scope not explicit")
    require(raw["target"]["triple"] == scope["effective_target"], "metadata/compiler target mismatch")
    require("--filter-platform" in data["metadata_command"]["command"] and
            "--target" in context["command"]["command"], "concrete target not used for both operations")
    artifact = context["cargo_compilation_artifact"]
    require(artifact["package_id"] == context["package"]["id"] and
            context["identity"]["actual_features"] == artifact["features"] and
            context["identity"]["actual_profile"] == artifact["profile"], "actual Cargo compilation context lost")
    require(data["experimental_provenance"] == {
        "bootstrap_inherited": "1", "bootstrap_set_by_rqlens": False,
    }, "experimental bootstrap was hidden or silently set")
    require(all("signature" not in item for item in data["items"]), "legacy signatures mixed into compiler items")
    for item in context["inventory"]["items"]:
        node = raw["index"][item["rustdoc_id"]]
        require(item["definition_docs"]["text"] == node["docs"] and
                item["name"] == node["name"], "definition/docs do not match actual compiler JSON")
    return context


def main_graph(data):
    context = completed_context(data)
    items = context["inventory"]["items"]
    named = {item["name"]: item for item in items}
    require({"Generated", "Reexported", "SecondAlias", "LocalDebugOnly", "Debug", "doc_only"} <= named.keys(),
            f"reachable generated/reexport/alias API missing: {sorted(str(k) for k in named)}")
    require(not {"Unreachable", "HiddenAtRoot", "HiddenInPrivate", "Private", "runtime_only", "private"}.intersection(named),
            "hidden/private/unreachable or runtime-only declaration treated as rustdoc-visible")
    require(("FeatureOnly" in named) == ("extra" in context["identity"]["actual_features"]),
            "compiled feature inventory disagrees with actual Cargo artifact")
    exported = named["Reexported"]["export_paths"]
    require(any(path[-1] == "PublicAlias" for path in exported) and
            all("implementation" not in path for path in exported), "private-module reexport path incorrect")
    edge = next(edge for edge in data["exports"] if edge.get("kind") == "reexport" and edge["path"][-1] == "PublicAlias")
    require(edge["reexport_docs"] != named["Reexported"]["definition_docs"]["text"] and
            edge["inherited_docs"] is None, "reexport/definition/rendered docs silently merged")
    require(named["SecondAlias"]["kind"] == "type_alias" and
            str(named["SecondAlias"]["definition"]["type"]["resolved_path"]["id"]) == named["Reexported"]["rustdoc_id"],
            "alias mistaken for a new nominal declaration")
    for name in ["Generated", "Reexported"]:
        item = named[name]
        require(item["standard_debug"]["status"] == "standard-debug-implementation-observed", f"std Debug not observed on {name}")
        witnessed = [row for row in item["implementations"] if row["standard_debug_identity"] is True]
        require(witnessed and all(row["trait_path"]["path"] == ["core", "fmt", "Debug"] and
                                 row["trait_origin"]["status"] == "probed-sysroot" for row in witnessed),
                "standard trait inferred from leaf name rather than compiler identity")
    local = named["LocalDebugOnly"]
    require(local["standard_debug"]["status"] != "standard-debug-implementation-observed", "own Debug trait mistaken for std Debug")
    require(any(row["trait_path"] and row["trait_path"]["path"][-1] == "Debug" and
                row["trait_path"]["crate_id"] == 0 and row["standard_debug_identity"] is False
                for row in local["implementations"]), "local trait identity witness lost")
    generated = named["Generated"]
    require(generated["source_attribution"]["not_fabricated_from_syntax"] is True and
            "not independently certified" in generated["source_attribution"]["status"],
            "macro expansion span falsely certified as an authored declaration")
    dependency = next(row for row in context["inventory"]["public_dependencies"]
                      if row["provenance"].get("binding", {}).get("package", {}).get("name") == "api-dependency")
    binding = dependency["provenance"]["binding"]
    require(dependency["provenance"]["status"] == "cargo-artifact-path-match" and
            binding["package"]["version"] == "0.0.0" and
            any(row["package_id"] == binding["package"]["id"] for row in context["dependency_compilation_artifacts"]),
            "public dependency identity not bound to actual same-invocation artifact")
    external = next(edge for edge in data["exports"] if edge.get("kind") == "reexport" and edge["path"][-1] == "ExternalAlias")
    require(external["target_id"] not in context["capture"]["raw_document"]["index"] and
            context["inventory"]["limitations"] and external["inherited_docs"] is None,
            "unknown external definition/inherited docs falsely resolved")
    return {"summary": data["summary"], "context_id": context["context_id"],
            "features": context["identity"]["actual_features"],
            "target": data["scope"]["effective_target"], "names": sorted(str(k) for k in named)}


def stale(tool, directory, config, phase, env):
    code = execute([tool, "check", "--config", config, "--fail-on", "partial"], directory, phase, env)
    report = json.loads((directory / "artifacts/policy_report.json").read_text())
    state = report["artifact_status"]["semantic_api.json"]
    require(code != 0 and state["status"].lower() == "stale", f"changed compilation input reused evidence: {state}")
    return state


def decoder_wrapper(directory, mode):
    actual = shutil.which("rustdoc")
    require(actual is not None, "real rustdoc required")
    path = directory / f"negative-{mode}-rustdoc.py"
    path.write_text(f'''#!{sys.executable}
# Explicit negative decoder fixture; never positive compiler proof.
import json, pathlib, subprocess, sys
args = sys.argv[1:]
code = subprocess.run([{actual!r}, *args], check=False).returncode
if code == 0 and "--crate-name" in args and ("--output-format" in args or "--output-format=json" in args):
    out = next((args[i+1] for i,a in enumerate(args[:-1]) if a in ("-o", "--out-dir")), None)
    name = args[args.index("--crate-name")+1]
    if out:
        target = pathlib.Path(out) / (name + ".json")
        if target.exists():
            original = target.read_bytes()
            pathlib.Path({str(directory / (mode + '-original-compiler.json'))!r}).write_bytes(original)
            if {mode!r} == "format":
                document = json.loads(original)
                document["format_version"] = 999
                target.write_text(json.dumps(document))
            else:
                target.write_text("intentionally malformed negative decoder input")
sys.exit(code)
''')
    path.chmod(0o755)
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rqlens", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--helper-manifest", type=Path, required=True)
    args = parser.parse_args()
    original = args.rqlens.resolve(strict=True)
    helper = args.helper_manifest.resolve(strict=True)
    root = args.output.resolve()
    root.mkdir(parents=True, exist_ok=False)
    tool = root / original.name
    shutil.copy2(original, tool)
    results = {"passed": False, "tool_sha256": hashlib.sha256(tool.read_bytes()).hexdigest(),
               "helper_manifest": str(helper), "cases": {}}

    def case(name, action):
        try:
            result = action()
            results["cases"][name] = {"passed": True, "evidence": result}
        except (OSError, ValueError, KeyError, StopIteration, AssertionError, subprocess.TimeoutExpired) as error:
            results["cases"][name] = {"passed": False, "error": str(error)}
        print(name, "PASS" if results["cases"][name]["passed"] else "FAIL",
              results["cases"][name].get("error", ""), flush=True)

    primary = root / "primary"
    setup(primary)
    config = write_config(primary, helper)
    experimental = environment(True)
    try:
        def disabled():
            write_config(primary, helper, backend=None)
            data = measure(tool, primary, config, "disabled", environment())
            require(data["summary"]["status"] == "disabled", "default backend changed")
            unavailable(data)
            return data["summary"]
        case("disabled-is-not-api-zero", disabled)

        def legacy():
            write_config(primary, helper, backend="cargo-public-api")
            data = measure(tool, primary, config, "legacy", environment())
            require(not data.get("contexts") and all("signature" in item and "rustdoc_id" not in item
                    for item in data["items"]), "legacy signatures promoted to compiler identities")
            return data["summary"]
        case("legacy-signatures-separate", legacy)

        def stable():
            write_config(primary, helper)
            data = measure(tool, primary, config, "stable", environment())
            unavailable(data)
            require(data["experimental_provenance"]["bootstrap_inherited"] is None and
                    data["experimental_provenance"]["bootstrap_set_by_rqlens"] is False,
                    "backend silently enabled bootstrap")
            return {"summary": data["summary"], "failures": data["failures"]}
        case("ordinary-stable-refusal", stable)
        def expanded():
            def authored(phase):
                require(execute([tool, "measure", "api-health", "--config", config], primary,
                                phase, experimental) == 0, "source-authored measurement failed")
                document = json.loads((primary / "artifacts/api_health.json").read_text())
                row = next(row for row in document["records"] if row["path"] == "src/lib.rs")
                keys = ["documentation_model_version", "public_item_count", "observed_public_item_count",
                        "documented_public_item_count", "observed_documented_public_item_count"]
                return {key: row[key] for key in keys}
            before = authored("authored-before")
            result = main_graph(measure(tool, primary, config, "expanded", experimental))
            after = authored("authored-after")
            require(before == after, "semantic capture silently replaced source-authored documentation counts")
            result["source_authored_counts_unchanged"] = after
            return result
        case("real-expanded-public-graph", expanded)

        def freshness():
            states = {}
            for key, value in (("CARGO_PROFILE_DEV_DEBUG_ASSERTIONS", "false"),
                               ("RUSTDOCFLAGS", "--cfg rqlens_semantic_probe"),
                               ("RUSTC_BOOTSTRAP", "0")):
                changed = dict(experimental); changed[key] = value
                states[key] = stale(tool, primary, config, "stale-" + key.lower(), changed)
            source = primary / "src/lib.rs"; before = source.read_text()
            source.write_text(before + "\n// New source requires fresh semantic evidence.\n")
            states["source"] = stale(tool, primary, config, "stale-source", experimental)
            source.write_text(before)
            return states
        case("source-and-compilation-environment-freshness", freshness)

        def features():
            write_config(primary, helper, features=("extra",))
            stale(tool, primary, config, "stale-feature-selection", experimental)
            data = measure(tool, primary, config, "extra", experimental)
            result = main_graph(data)
            context = completed_context(data)
            require("FeatureOnly" in result["names"] and "extra" in context["identity"]["actual_features"],
                    "feature selection not reflected in actual compiler inventory")
            return result
        case("selected-feature-real-capture", features)

        def failed_capture():
            prior = json.loads((primary / "extra-report.json").read_text())["data"]
            (primary / "src/lib.rs").write_text(BROKEN_CYCLE)
            data = measure(tool, primary, config, "failed-cycle", experimental)
            unavailable(data)
            require(data["contexts"] and all(c["status"] != "completed" and
                    not c.get("capture", {}).get("raw_document") for c in data["contexts"]),
                    "failed compiler output was parsed/reused")
            previous = {c["capture"]["private_target_directory"] for c in prior["contexts"]}
            require(all(c["capture"]["private_target_directory"] not in previous and
                        c["capture"]["output_reused_after_failure"] is False for c in data["contexts"]),
                    "capture reused prior target output")
            return {"summary": data["summary"], "failures": data["failures"]}
        case("failed-real-compile-never-reuses-prior-output", failed_capture)

        def cycle():
            directory = root / "valid-glob-cycle"; setup(directory, GLOB_CYCLE)
            cfg = write_config(directory, helper)
            data = measure(tool, directory, cfg, "cycle", experimental)
            context = completed_context(data)
            require(context["inventory"]["limitations"] and data["summary"]["item_count"] is None,
                    "cyclic glob expansion silently certified")
            require(any(item["name"] == "Terminal" for item in data["items"]), "real reachable terminal lost")
            return {"summary": data["summary"], "limitations": context["inventory"]["limitations"]}
        case("real-cyclic-glob-partial-join", cycle)

        def workspace():
            directory = root / "workspace"; setup(directory)
            (directory / "second/src").mkdir(parents=True)
            (directory / "second/Cargo.toml").write_text('[package]\nname="semantic-secondary"\nversion="0.0.0"\nedition="2024"\n')
            (directory / "second/src/lib.rs").write_text('//! A deliberately excluded library.\npub struct Secondary;\n')
            with (directory / "Cargo.toml").open("a") as manifest:
                manifest.write('\n[workspace]\nmembers=[".","second"]\nexclude=["dependency"]\nresolver="3"\n')
            require(execute(["cargo", "generate-lockfile", "--offline", "--manifest-path", directory / "Cargo.toml"],
                            directory, "workspace-lock") == 0, "workspace lock failed")
            cfg = write_config(directory, helper, workspace=True, exclude=("semantic-secondary",))
            data = measure(tool, directory, cfg, "workspace", experimental)
            require(data["metadata_command"]["stdout_truncated"] is False, "fixture metadata truncated")
            metadata = json.loads(data["metadata_command"]["stdout_tail"])
            selected = {package["id"] for package in metadata["packages"]
                        if package["id"] in metadata["workspace_members"] and
                        package["name"] != "semantic-secondary"}
            contexts = data["contexts"]
            require({context["package"]["id"] for context in contexts} == selected and
                    all(context["status"] == "completed" for context in contexts) and
                    not any(item["name"] == "Secondary" for item in data["items"]),
                    "actual Cargo membership/exclusion disagrees with captured libraries")
            require(len({context["context_id"] for context in contexts}) == len(contexts),
                    "distinct Cargo library contexts were merged")
            return {"summary": data["summary"], "selected_package_ids": sorted(selected),
                    "scope": data["scope"]}
        case("workspace-library-selection", workspace)

        for name in ["unavailable", "format", "malformed", "private"]:
            def negative(name=name):
                directory = root / ("negative-" + name); setup(directory)
                cfg = write_config(directory, helper)
                env = environment(True)
                if name == "unavailable":
                    env["RUSTDOC"] = str(directory / "not-installed-rustdoc")
                elif name == "private":
                    env["RUSTDOCFLAGS"] = "--document-private-items"
                else:
                    env["RUSTDOC"] = str(decoder_wrapper(directory, name))
                data = measure(tool, directory, cfg, name, env)
                unavailable(data)
                if name == "format":
                    require(any(c.get("capture", {}).get("raw_document", {}).get("format_version") == 999
                                for c in data["contexts"]), "negative format mutation was not exercised")
                if name == "private":
                    require(any(c.get("capture", {}).get("raw_document", {}).get("includes_private") is True
                                for c in data["contexts"]), "real private-item compiler capture was not exercised")
                return {"summary": data["summary"], "failures": data["failures"]}
            case("negative-" + name, negative)
        results["passed"] = all(item["passed"] for item in results["cases"].values())
    finally:
        (root / "summary.json").write_text(json.dumps(results, indent=2) + "\n")
    return 0 if results["passed"] else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, AssertionError, subprocess.TimeoutExpired) as error:
        print(f"semantic API consumer probe failed: {error}", file=sys.stderr)
        sys.exit(1)
